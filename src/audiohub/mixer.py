"""Validated per-source mixer state and PipeWire filter-chain configuration.

This module creates three *virtual* stereo inputs with separate parametric EQ.
It does not itself prove physical device playback or implement a hard limiter.
"""
from __future__ import annotations

import math

CHANNELS = ("music", "laptop", "tablet")
EQ_BANDS = ("bass", "mid", "treble")
DEFAULT_VOLUME = {"music": 65, "laptop": 50, "tablet": 50}


def _integer(value, lower, upper):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError("integer value required")
    if not math.isfinite(value) or int(value) != value:
        raise ValueError("finite integer required")
    number = int(value)
    if not lower <= number <= upper:
        raise ValueError("value out of range")
    return number


def defaults():
    state = {"master": 70}
    for channel in CHANNELS:
        state[channel] = {
            "volume": DEFAULT_VOLUME[channel],
            "bass": 0, "mid": 0, "treble": 0, "mute": False,
        }
    return state


def patch_settings(current, patch):
    """Apply a partial API patch with strict field and type validation."""
    if not isinstance(current, dict) or not isinstance(patch, dict):
        raise ValueError("settings must be objects")
    if set(patch) - (set(CHANNELS) | {"master"}):
        raise ValueError("unknown control")
    result = defaults()
    for name in CHANNELS:
        if name in current:
            value = current[name]
            if not isinstance(value, dict):
                raise ValueError("invalid current channel")
            result[name].update(value)
    if "master" in current:
        result["master"] = current["master"]
    if "master" in patch:
        result["master"] = patch["master"]
    for name in CHANNELS:
        if name not in patch:
            continue
        section = patch[name]
        if not isinstance(section, dict):
            raise ValueError("channel settings must be objects")
        if set(section) - {"volume", "mute", *EQ_BANDS}:
            raise ValueError("unknown channel control")
        result[name].update(section)
    result["master"] = _integer(result["master"], 0, 100)
    for name in CHANNELS:
        control = result[name]
        control["volume"] = _integer(control["volume"], 0, 100)
        for band in EQ_BANDS:
            control[band] = _integer(control[band], -12, 12)
        if not isinstance(control["mute"], bool):
            raise ValueError("mute must be a boolean")
    return result


def pipewire_filter_config(settings):
    """Render three stereo virtual sinks (requires actual PipeWire validation)."""
    settings = patch_settings(defaults(), settings)
    blocks = ["# Generated by AudioHub. Do not hand-edit.", "context.modules = ["]
    for channel in CHANNELS:
        ctl = settings[channel]
        blocks.append(
            """
  {
    name = libpipewire-module-filter-chain
    args = {
      node.description = "AudioHub %s equalizer"
      filter.graph = {
        nodes = [
          { type = builtin name = eq label = param_eq
            config = { filters = [
              { type = bq_lowshelf freq = 110 q = 0.707 gain = %d }
              { type = bq_peaking freq = 1000 q = 1.0 gain = %d }
              { type = bq_highshelf freq = 7000 q = 0.707 gain = %d }
            ] }
          }
        ]
      }
      capture.props = {
        node.name = "audiohub.%s"
        media.class = "Audio/Sink"
        audio.channels = 2
        audio.position = [ FL FR ]
      }
      playback.props = {
        node.name = "audiohub.%s.output"
        node.passive = true
        audio.channels = 2
        audio.position = [ FL FR ]
      }
    }
  }""" % (channel, ctl["bass"], ctl["mid"], ctl["treble"], channel, channel)
        )
    blocks.append("]")
    return "\n".join(blocks) + "\n"


def volume_commands(settings, sink_ids, output_id=None):
    """Return argv lists; commands are *not* executed here."""
    settings = patch_settings(defaults(), settings)
    commands = []
    for channel in CHANNELS:
        if channel not in sink_ids:
            continue
        node_id = str(int(sink_ids[channel]))
        commands.append(["wpctl", "set-volume", node_id, str(settings[channel]["volume"] / 100)])
        commands.append(["wpctl", "set-mute", node_id, "1" if settings[channel]["mute"] else "0"])
    if output_id is not None:
        commands.append(["wpctl", "set-volume", str(int(output_id)), str(settings["master"] / 100)])
    return commands
