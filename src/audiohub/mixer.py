"""Validated per-source mixer state and PipeWire filter-chain configuration.

This module creates three *virtual* stereo inputs with separate parametric EQ.
It does not itself prove physical device playback or implement a hard limiter.
"""
from __future__ import annotations

import math

CHANNELS = ("music", "laptop", "tablet")
EQ_BANDS = ("bass", "mid", "treble")
DEFAULT_VOLUME = {"music": 65, "laptop": 50, "tablet": 50}


def _integer(value, lower, upper):
    """Validate integer controls without converting arbitrary-size ints to float.

    math.isfinite(10**400) raises OverflowError instead of rejecting the
    value as an ordinary invalid control. Bound native ints before any
    conversion; accept only finite, integral builtin floats in range.
    """
    if type(value) is int:
        if lower <= value <= upper:
            return value
        raise ValueError("value out of range")
    if type(value) is not float:
        raise ValueError("integer value required")
    if not math.isfinite(value) or not lower <= value <= upper or not value.is_integer():
        raise ValueError("finite integer in range required")
    return int(value)


def defaults():
    state = {"master": 70}
    for channel in CHANNELS:
        state[channel] = {
            "volume": DEFAULT_VOLUME[channel],
            "bass": 0, "mid": 0, "treble": 0, "mute": False,
        }
    return state


def patch_settings(current, patch):
    """Apply a partial API patch with strict field and type validation."""
    if not isinstance(current, dict) or not isinstance(patch, dict):
        raise ValueError("settings must be objects")
    if set(patch) - (set(CHANNELS) | {"master"}):
        raise ValueError("unknown control")
    result = defaults()
    for name in CHANNELS:
        if name in current:
            value = current[name]
            if not isinstance(value, dict):
                raise ValueError("invalid current channel")
            result[name].update(value)
    if "master" in current:
        result["master"] = current["master"]
    if "master" in patch:
        result["master"] = patch["master"]
    for name in CHANNELS:
        if name not in patch:
            continue
        section = patch[name]
        if not isinstance(section, dict):
            raise ValueError("channel settings must be objects")
        if set(section) - {"volume", "mute", *EQ_BANDS}:
            raise ValueError("unknown channel control")
        result[name].update(section)
    result["master"] = _integer(result["master"], 0, 100)
    for name in CHANNELS:
        control = result[name]
        control["volume"] = _integer(control["volume"], 0, 100)
        for band in EQ_BANDS:
            control[band] = _integer(control[band], -12, 12)
        if not isinstance(control["mute"], bool):
            raise ValueError("mute must be a boolean")
    return result


def pipewire_filter_config(settings):
    """Render three stereo virtual sinks (requires actual PipeWire validation)."""
    settings = patch_settings(defaults(), settings)
    blocks = ["# Generated by AudioHub. Do not hand-edit.", "context.modules = ["]
    for channel in CHANNELS:
        ctl = settings[channel]
        blocks.append(
            """
  {
    name = libpipewire-module-filter-chain
    args = {
      node.description = "AudioHub %s equalizer"
      filter.graph = {
        nodes = [
          { type = builtin name = eq label = param_eq
            config = { filters = [
              { type = bq_lowshelf freq = 110 q = 0.707 gain = %d }
              { type = bq_peaking freq = 1000 q = 1.0 gain = %d }
              { type = bq_highshelf freq = 7000 q = 0.707 gain = %d }
            ] }
          }
        ]
      }
      capture.props = {
        node.name = "audiohub.%s"
        media.class = "Audio/Sink"
        audio.channels = 2
        audio.position = [ FL FR ]
      }
      playback.props = {
        node.name = "audiohub.%s.output"
        node.passive = true
        audio.channels = 2
        audio.position = [ FL FR ]
      }
    }
  }""" % (channel, ctl["bass"], ctl["mid"], ctl["treble"], channel, channel)
        )
    blocks.append("]")
    return "\n".join(blocks) + "\n"


def mix_gain_budget(settings):
    """Return a conservative amplitude attenuation for all three inputs.

    The estimate assumes every unmuted input may be simultaneously at full
    scale. It accounts for the sum of positive EQ band gains per channel, but
    is not a true look-ahead limiter or a substitute for measured peak tests.
    """
    settings = patch_settings(defaults(), settings)
    worst_case = math.fsum(
        (control["volume"] / 100) * 10 ** (
            sum(max(0, control[band]) for band in EQ_BANDS) / 20
        )
        for channel in CHANNELS
        for control in (settings[channel],)
        if not control["mute"]
    )
    return min(1.0, 1.0 / worst_case) if worst_case > 0 else 1.0


def effective_master_gain(settings):
    """Constrain the requested master level to the conservative mix budget."""
    settings = patch_settings(defaults(), settings)
    return (settings["master"] / 100) * mix_gain_budget(settings)


MAX_PIPEWIRE_NODE_ID = 2**31 - 1


def _validated_wpctl_targets(sink_ids, output_id):
    """Reject missing/ambiguous identity before returning ANY control command.

    Production PipeWire discovery already bounds IDs, but this boundary
    must not turn a boolean, float or device name into a different target.
    """
    if type(sink_ids) is not dict or any(channel not in CHANNELS for channel in sink_ids):
        raise ValueError("Unknown mixer target channel")
    used = set()
    if output_id is not None:
        if type(output_id) is not int or not 0 <= output_id <= MAX_PIPEWIRE_NODE_ID:
            raise ValueError("Invalid physical output node ID")
        used.add(output_id)
    for node_id in sink_ids.values():
        if (type(node_id) is not int
                or not 0 <= node_id <= MAX_PIPEWIRE_NODE_ID
                or node_id in used):
            raise ValueError("Invalid or repeated mixer target node ID")
        used.add(node_id)
    return sink_ids


def volume_commands(settings, sink_ids, output_id=None):
    """Return argv lists; commands are *not* executed here."""
    settings = patch_settings(defaults(), settings)
    sink_ids = _validated_wpctl_targets(sink_ids, output_id)
    commands = []
    # Apply the conservative master gain before per-input volume/unmute.
    # A failed master command must never leave a newly admitted source live.
    if output_id is not None:
        commands.append(["wpctl", "set-volume", str(output_id), str(effective_master_gain(settings))])
    for channel in CHANNELS:
        if channel not in sink_ids:
            continue
        node_id = str(sink_ids[channel])
        commands.append(["wpctl", "set-volume", node_id, str(settings[channel]["volume"] / 100)])
        commands.append(["wpctl", "set-mute", node_id, "1" if settings[channel]["mute"] else "0"])
    return commands
